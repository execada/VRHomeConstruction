/**
 * Типы подсказок редактора и обучения.
 * @module hints/types
 */

/** Состояние подсказок и обучения. */
export interface HintsState {
  /** Показывать подсказки («здесь выберите модели», «сюда — дизайн») */
  enabled: boolean;
  /** Подсказки, которые пользователь закрыл кнопкой «Понятно» */
  dismissed: string[];
  /** Текущий шаг обучения (null — обучение не идёт) */
  tourStep: number | null;
  /** Обучение пройдено или закрыто — само больше не предлагается */
  tourDone: boolean;
}
